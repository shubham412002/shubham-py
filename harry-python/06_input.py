# rules for defining variables  
# 1. variable name can contain alphabet, digit and underscore
# 1. variable name should not start with number
# 2. variable name should not contain special characters except underscore like @, #, $, %, etc.
# 3. variable name should not be a keyword
# 4. variable name should not contain space


